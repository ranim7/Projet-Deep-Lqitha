"""Generate prompts/PROMPT_LIBRARY.md (deliverable 3) from prompts.yaml + measured v1/v2 results."""
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from lqitha import config  # noqa: E402
from lqitha.evalutil import md_table  # noqa: E402

P = yaml.safe_load((ROOT / "prompts" / "prompts.yaml").read_text(encoding="utf-8"))
R = json.loads((config.RESULTS / "prompt_eval.json").read_text(encoding="utf-8")) if (config.RESULTS / "prompt_eval.json").exists() else {}
M = json.loads((config.RESULTS / "matching_eval.json").read_text(encoding="utf-8")) if (config.RESULTS / "matching_eval.json").exists() else {}
EVAL_KEY = {"intake": "intake", "perception": "perception", "verifier": None, "procedure": "procedure",
            "notifier": "notifier", "claim_check": "claim_check"}
MODEL_NAME = {"FAST_MODEL": config.FAST_MODEL, "TEXT_MODEL": config.TEXT_MODEL, "VISION_MODEL": config.VISION_MODEL}

out = ["# Lqitha - Prompt library\n",
       "Single source of truth: `prompts/prompts.yaml` (this file is generated by `scripts/build_n8n.py` companion "
       "`scripts/build_prompt_library.py`). The **active** version of each prompt is injected into the n8n workflow by "
       "`scripts/build_n8n.py`; v1 and v2 are both evaluated by `scripts/eval_prompts.py` / `scripts/eval_matching.py` "
       "on fixed test sets with the same model, so the before/after numbers below are directly comparable.\n",
       "| Prompt | Agent | Model (free, Groq) | Active | Techniques in the active version |", "|---|---|---|---|---|"]
for name, p in P.items():
    v = p["versions"][p["active"]]
    model = MODEL_NAME.get(p['model'], p['model']) + (f" (text-only: {MODEL_NAME.get(p['text_only_model'])})" if p.get('text_only_model') else "")
    out.append(f"| `{name}` | {p['agent']} | {model} | {p['active']} | {', '.join(v['techniques'])} |")

for name, p in P.items():
    out += [f"\n---\n\n## `{name}` - {p['agent']}\n", f"**Role in the system.** {p['role_in_system'].strip()}\n",
            f"**Model:** {MODEL_NAME.get(p['model'], p['model'])} - temperature {p.get('temperature', 0)} - output: {p.get('output')} - "
            f"**active version: {p['active']}**\n"]
    key = EVAL_KEY.get(name)
    if key and key in R:
        out += ["### Measured before / after\n", md_table(R[key]["summary"], list(R[key]["summary"][0].keys())), ""]
    if name == "verifier" and "verifier" in M:
        out += ["### Measured before / after (top-2 matcher candidates, real items)\n",
                md_table(M["verifier"], list(M["verifier"][0].keys())), ""]
    out += ["### Failure cases observed and fixes\n", "| id | seen in | failure | fix |", "|---|---|---|---|"]
    for f in p.get("failures_and_fixes", []):
        out.append(f"| {f['id']} | {f['observed_in']} | {f['failure']} | {f['fix']} |")
    for vname, v in p["versions"].items():
        out += [f"\n### Version {vname} - techniques: {', '.join(v['techniques'])}\n", "**System prompt**\n",
                "```text", v["system"].rstrip(), "```", "**User template**\n", "```text", v["user"].rstrip(), "```"]

(ROOT / "prompts" / "PROMPT_LIBRARY.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print("wrote prompts/PROMPT_LIBRARY.md")
